def sku_info(part: str, totaal: int) -> dict:
    naam, uitleg = SKU_INFO.get(part, (part.replace('_', ' ').strip(), ''))
    gratis = (totaal >= 1000 or re.search(r'(?i)gratis|proef|trial|lighthouse|windows store|virtu', naam) is not None
              or re.search(r'(?i)FREE|VIRAL|TRIAL|STORE|VIRTUALUSER', part) is not None)
    return {'name': naam, 'desc': uitleg, 'kind': 'gratis' if gratis else 'betaald'}
